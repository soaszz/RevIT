import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const suite = read("supabase/tests/trusted_cutover_verification.sql");
const rollback = read("supabase/rollbacks/202610160027_trusted_cutover_and_attempt_numbering_rollback.sql");
assert.match(suite, /\nrollback;\s*$/);
assert.match(rollback, /^--[^\n]*\nbegin;\n[\s\S]*\ncommit;\s*$/);
const body = rollback.slice(rollback.indexOf("begin;\n") + 7).replace(/\ncommit;\s*$/, "\n");
assert.doesNotMatch(body, /^\s*(?:begin|commit|rollback);/im);
const capture = table => `(select coalesce(jsonb_agg(to_jsonb(r) order by to_jsonb(r)::text),'[]'::jsonb) from public.${table} r)`;
const tables = ["question_attempts", "study_sessions", "activity_events", "daily_activity", "user_progress", "user_achievements", "question_reinforcement"];
const snapshot = tables.map(table => `'${table}',${capture(table)}`).join(",\n");
const output = `-- GENERATED by scripts/phase3n/prepare-cutover-rollback.mjs. PREPARATION ONLY; no database was accessed.
-- Same isolated-target/empty-database safeguards as the base suite. All SQL below is one rollback transaction.
${suite.replace(/\nrollback;\s*$/, "\n")}
create temporary table rollback_snapshot on commit drop as select jsonb_build_object(${snapshot}) as data;
-- Exact current rollback body, with only its outer BEGIN/COMMIT removed to prevent accidental commits.
${body}
do $$
begin
  if (select data from rollback_snapshot) is distinct from jsonb_build_object(${snapshot}) then
    raise exception '14: rollback changed durable study/reward data';
  end if;
  if not exists(select 1 from public.trusted_study_config where id = 1 and enabled = false) then
    raise exception '14: rollback did not disable configuration';
  end if;
  perform pg_temp.expect_error('select public.assert_trusted_study_enabled()', 'PT503');
  perform pg_temp.expect_error('select public.create_verified_study_session(null,null,null,null)', 'PT503');
  perform pg_temp.expect_error('select public.commit_verified_study_batch(null,null,null)', 'PT503');
  if exists(select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname in ('create_verified_study_session','commit_verified_study_batch','leaderboard_metric_rows')
      and (has_function_privilege('anon',p.oid,'EXECUTE') or has_function_privilege('authenticated',p.oid,'EXECUTE'))) then
    raise exception '14: rollback reopened browser RPC execution';
  end if;
end $$;
insert into trusted_test_results values('14_rollback_stubs_preserve_data','PASS');
select * from trusted_test_results order by scenario;
rollback;
`;
assert.doesNotMatch(output, /^\s*commit;/im);
writeFileSync(new URL("supabase/tests/trusted_cutover_rollback_verification.sql", root), output);
console.log("Prepared rollback verification SQL; no database access or SQL execution.");
